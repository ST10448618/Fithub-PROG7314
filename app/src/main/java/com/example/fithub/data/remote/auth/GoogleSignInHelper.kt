package com.example.fithub.data.remote.auth

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.GetCredentialResponse
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.example.fithub.R
import com.example.fithub.core.LogTags
import com.example.fithub.core.Resource
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException

/**
 * Minimal data returned by a successful Google sign-in. The `idToken` is
 * short-lived (~1 h); we exchange it via Firebase immediately, so callers never
 * persist it.
 */
data class GoogleAccount(
    val idToken: String,
    val email: String,
    val displayName: String
)

/**
 * Credential Manager wrapper for "Sign in with Google".
 *
 * This class NEVER touches Firebase — it only resolves the Google identity.
 * The resulting ID token is handed to
 * [com.example.fithub.domain.repository.AuthRepository.signInWithGoogle].
 *
 * Reference: https://developer.android.com/training/id-auth/identify
 *            https://developer.android.com/identity/sign-in/credential-manager-siwg
 *            https://firebase.google.com/docs/auth/android/google-signin
 * (accessed February 2026)
 */
class GoogleSignInHelper(private val context: Context) {

    private val credentialManager = CredentialManager.create(context)

    /**
     * Launches the Google identity sheet. Blocks the calling coroutine until
     * the user completes/cancels. Never throws — returns [Resource.Error] with
     * a friendly, already-resolved user message for every failure mode.
     *
     * @param serverClientId value of `R.string.default_web_client_id`
     *   generated by the Google Services Gradle plugin once the Google provider
     *   is enabled in the Firebase Console.
     */
    suspend fun signIn(serverClientId: String): Resource<GoogleAccount> {
        if (serverClientId.isBlank()) {
            Log.w(LogTags.AUTH, "Google sign-in attempted without a server client id")
            return Resource.Error(context.getString(R.string.auth_google_error_no_client_id))
        }
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(serverClientId)
            .setAutoSelectEnabled(false)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(option)
            .build()

        return try {
            val response: GetCredentialResponse =
                credentialManager.getCredential(context, request)
            val credential = response.credential
            when (credential) {
                is CustomCredential -> {
                    if (credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                        parseGoogleCredential(credential)
                    } else {
                        Log.w(LogTags.AUTH, "Unexpected custom credential type=${credential.type}")
                        Resource.Error(context.getString(R.string.auth_google_error_generic))
                    }
                }
                else -> {
                    Log.w(LogTags.AUTH, "Unexpected credential type=${credential.type}")
                    Resource.Error(context.getString(R.string.auth_google_error_generic))
                }
            }
        } catch (c: GetCredentialCancellationException) {
            Log.i(LogTags.AUTH, "Google sign-in cancelled by user")
            Resource.Error(context.getString(R.string.auth_google_error_cancelled))
        } catch (n: NoCredentialException) {
            Log.w(LogTags.AUTH, "No Google account on device")
            Resource.Error(context.getString(R.string.auth_google_error_no_account))
        } catch (g: GetCredentialException) {
            Log.e(LogTags.AUTH, "Credential Manager failed: ${g.errorMessage}", g)
            val msg = (g.message ?: "").lowercase()
            val userMsg = if ("network" in msg) {
                context.getString(R.string.auth_google_error_network)
            } else {
                context.getString(R.string.auth_google_error_generic)
            }
            Resource.Error(userMsg)
        } catch (t: Throwable) {
            Log.e(LogTags.AUTH, "Unexpected Google sign-in failure", t)
            Resource.Error(context.getString(R.string.auth_google_error_generic))
        }
    }

    private fun parseGoogleCredential(credential: CustomCredential): Resource<GoogleAccount> =
        try {
            val g = GoogleIdTokenCredential.createFrom(credential.data)
            Log.i(LogTags.AUTH, "Google identity resolved for email=${g.id} (token redacted)")
            Resource.Success(
                GoogleAccount(
                    idToken = g.idToken,
                    email = g.id,
                    displayName = g.displayName ?: g.id.substringBefore("@")
                )
            )
        } catch (p: GoogleIdTokenParsingException) {
            Log.e(LogTags.AUTH, "Google ID token parse failed", p)
            Resource.Error(context.getString(R.string.auth_google_error_generic))
        }
}